import pandas as pd
import pyproj
import matplotlib.pyplot as plt


class UTMTransformationPipeline:
    """
    Automated Geomatics Pipeline for Bidirectional UTM/Geographic
    Coordinate Transformations, Batch Processing, and Residual Analysis.
    """

    def __init__(self, geographic_crs="EPSG:4326"):
        """Initializes pipeline with base WGS84 Geographic CRS."""
        self.geographic_crs = geographic_crs

    def get_utm_epsg(self, lat: float, lon: float) -> tuple[int, str, str]:
        """Determines UTM Zone, Hemisphere, and corresponding EPSG Code."""
        zone = int((lon + 180) // 6) + 1
        is_northern = lat >= 0
        hemisphere = "N" if is_northern else "S"
        epsg_code = f"EPSG:{32600 + zone}" if is_northern else f"EPSG:{32700 + zone}"
        return zone, hemisphere, epsg_code

    def step1_forward_convert(self, df: pd.DataFrame) -> pd.DataFrame:
        """Converts raw Geographic coordinates (Lat/Long) to UTM (Easting/Northing)."""
        eastings, northings, zones, hemispheres, epsgs = [], [], [], [], []

        for _, row in df.iterrows():
            lat, lon = row["Latitude"], row["Longitude"]
            zone, hemi, target_epsg = self.get_utm_epsg(lat, lon)

            transformer = pyproj.Transformer.from_crs(
                self.geographic_crs, target_epsg, always_xy=True
            )
            easting, northing = transformer.transform(lon, lat)

            eastings.append(round(easting, 3))
            northings.append(round(northing, 3))
            zones.append(zone)
            hemispheres.append(hemi)
            epsgs.append(target_epsg)

        df_res = df.copy()
        df_res["UTM_Easting_m"] = eastings
        df_res["UTM_Northing_m"] = northings
        df_res["UTM_Zone"] = zones
        df_res["Hemisphere"] = hemispheres
        df_res["EPSG_Code"] = epsgs
        return df_res

    def step2_reverse_convert(self, df_utm: pd.DataFrame) -> pd.DataFrame:
        """Converts UTM dataset directly back to Geographic coordinates (Lat/Long)."""
        calc_lats, calc_lons = [], []

        for _, row in df_utm.iterrows():
            easting = row["UTM_Easting_m"]
            northing = row["UTM_Northing_m"]
            zone = int(row["UTM_Zone"])
            hemi = row["Hemisphere"]

            epsg_code = f"EPSG:{32600 + zone}" if hemi == "N" else f"EPSG:{32700 + zone}"
            transformer = pyproj.Transformer.from_crs(
                epsg_code, self.geographic_crs, always_xy=True
            )
            lon, lat = transformer.transform(easting, northing)

            calc_lats.append(round(lat, 6))
            calc_lons.append(round(lon, 6))

        df_res = df_utm.copy()
        df_res["Calculated_Latitude"] = calc_lats
        df_res["Calculated_Longitude"] = calc_lons
        return df_res


def main():
    pipeline = UTMTransformationPipeline()

    # STEP 1: INITIAL INPUT DATASET
    print("=== STEP 1: INITIAL GEOGRAPHIC DATASET (LAT/LONG) ===")
    input_data = pd.DataFrame({
        'Point_ID': ['P001', 'P002', 'P003', 'P004', 'P005', 'P006', 'P007', 'P008'],
        'Latitude':  [0.347600, 0.352100, 0.358900, 0.361000, 0.365500, 0.370200, 0.374800, 0.380100],
        'Longitude': [32.582500, 32.589000, 32.595500, 32.601000, 32.608500, 32.614200, 32.620100, 32.627800]
    })
    print(input_data)

    # STEP 2: FORWARD CONVERSION
    print("\n=== STEP 2: CONVERTING TO UTM GRID COORDINATES ===")
    utm_dataset = pipeline.step1_forward_convert(input_data)
    print(utm_dataset[['Point_ID', 'Latitude', 'Longitude', 'UTM_Easting_m', 'UTM_Northing_m', 'UTM_Zone', 'Hemisphere', 'EPSG_Code']])
    utm_dataset.to_csv("step2_utm_converted_output.csv", index=False)

    # Plot Forward Results
    plt.figure(figsize=(8, 4))
    plt.scatter(
        utm_dataset['UTM_Easting_m'], utm_dataset['UTM_Northing_m'],
        c='navy', s=80, edgecolors='black'
    )
    for _, row in utm_dataset.iterrows():
        plt.annotate(
            f"{row['Point_ID']}\nZone {row['UTM_Zone']}{row['Hemisphere']}",
            (row['UTM_Easting_m'], row['UTM_Northing_m']),
            textcoords="offset points", xytext=(0, 6), ha='center', fontsize=8
        )
    plt.title("Step 2 Output: Converted UTM Grid Coordinates")
    plt.xlabel("Easting (Meters)")
    plt.ylabel("Northing (Meters)")
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.tight_layout()
    plt.show()

    # STEP 3: REVERSE CONVERSION & RESIDUAL CHECK
    print("\n=== STEP 3: REVERSING FROM UTM BACK TO GEOGRAPHIC ===")
    final_dataset = pipeline.step2_reverse_convert(utm_dataset)

    # Residual Error Calculation
    final_dataset['Lat_Diff'] = round(final_dataset['Calculated_Latitude'] - final_dataset['Latitude'], 6)
    final_dataset['Lon_Diff'] = round(final_dataset['Calculated_Longitude'] - final_dataset['Longitude'], 6)

    print(final_dataset[['Point_ID', 'UTM_Easting_m', 'UTM_Northing_m', 'Latitude', 'Calculated_Latitude', 'Lat_Diff', 'Longitude', 'Calculated_Longitude', 'Lon_Diff']])
    final_dataset.to_csv("Final_bidirectional_pipeline_results.csv", index=False)

    # Plot Reverse Results
    plt.figure(figsize=(8, 4))
    plt.scatter(
        final_dataset['Calculated_Longitude'], final_dataset['Calculated_Latitude'],
        c='darkgreen', marker='s', s=80, edgecolors='black'
    )
    for _, row in final_dataset.iterrows():
        plt.annotate(
            f"{row['Point_ID']}",
            (row['Calculated_Longitude'], row['Calculated_Latitude']),
            textcoords="offset points", xytext=(0, 6), ha='center', fontsize=8
        )
    plt.title("Step 3 Output: Reversed Geographic Coordinates (Lat/Long)")
    plt.xlabel("Longitude (Degrees)")
    plt.ylabel("Latitude (Degrees)")
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.tight_layout()
    plt.show()


if __name__ == "__main__":
    main()

